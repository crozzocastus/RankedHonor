/**
 * Helper function to get match by ID
 */
export function getMatchById(matchId: string): MatchHistoryEntry | undefined {
  return mockMatchHistory.find((match) => match.id === matchId);
}

/**
 * Helper function to get recent matches
 */
export function getRecentMatches(limit: number = 20): MatchHistoryEntry[] {
  return mockMatchHistory.slice(0, limit);
}

/**
 * Helper function to get matches by hero
 */
export function getMatchesByHero(heroId: string): MatchHistoryEntry[] {
  return mockMatchHistory.filter((match) => match.heroPlayed === heroId);
}

/**
 * Helper function to get matches by game mode
 */
export function getMatchesByGameMode(gameMode: string): MatchHistoryEntry[] {
  return mockMatchHistory.filter((match) => match.gameMode === gameMode);
}

/**
 * Helper function to get matches by result
 */
export function getMatchesByResult(result: "victory" | "defeat"): MatchHistoryEntry[] {
  return mockMatchHistory.filter((match) => match.result === result);
}

